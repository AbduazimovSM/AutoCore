    private function createCategories(array $categories, ?int $parentId = null): void
    {
        foreach ($categories as $key => $value) {

            if (is_array($value)) {
                $name = $key;
                $children = $value;
            } else {
                $name = $value;
                $children = [];
            }

            $category = Reference::updateOrCreate(
                [
                    'type' => 'category',
                    'name' => $name,
                ],
                [
                    'code' => null,
                    'short_name' => null,
                    'parent_id' => $parentId,
                    'image' => 'default.png',
                    'description' => null,
                    'status' => true,
                ]
            );

            if (!empty($children)) {
                $this->createCategories(
                    $children,
                    $category->id
                );
            }
        }
    }

